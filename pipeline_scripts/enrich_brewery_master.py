def calculate_era(year):
    if not year:
        return "", "", 0
    try:
        y = int(str(year).strip())
    except Exception:
        return "", "", 0
    
    if y <= 0 or y > 2030:
        return "", "", 0
    
    current_year = 2026
    is_shinise = 1 if (current_year - y) >= 100 else 0
    
    for start, end, era_name, category in ERAS:
        if start <= y < end or (start <= y <= end and end == 9999):
            offset = y - start + 1
            era_str = f"{era_name}元年" if offset == 1 else f"{era_name}{offset}年"
            return era_str, category, is_shinise
    
    if y < 1141:
        return f"平安以前({y}年)", "古代・中世", 1
    return f"{y}年", "近代", is_shinise

