def enrich_brewery_database():
    print("[*] データベースに接続中...")
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()

    # 1. カラムの存在確認と追加 (ALTER TABLE)
    new_columns = [
        ("founded_era", "TEXT"),
        ("era_category", "TEXT"),
        ("is_shinise", "INTEGER DEFAULT 0"),
        ("water_source_name", "TEXT"),
        ("water_hardness_type", "TEXT"),
        ("toji_guild", "TEXT"),
        ("tour_info", "TEXT"),
        ("has_tasting", "INTEGER DEFAULT 0"),
        ("has_cafe_restaurant", "INTEGER DEFAULT 0"),
        ("is_cultural_property", "INTEGER DEFAULT 0"),
        ("cultural_property_desc", "TEXT")
    ]

    cursor.execute("PRAGMA table_info(breweries)")
    existing_cols = [c[1] for c in cursor.fetchall()]

    for col_name, col_type in new_columns:
        if col_name not in existing_cols:
            print(f"  [+] 新規カラム追加: breweries.{col_name} ({col_type})")
            cursor.execute(f"ALTER TABLE breweries ADD COLUMN {col_name} {col_type}")

    conn.commit()

    # 2. 全酒蔵データの取得
    cursor.execute("""
        SELECT id, name, name_norm, prefecture, city, address, founded_year, description, visitation_allowed, shop_available
        FROM breweries
    """)
    rows = cursor.fetchall()
    print(f"[*] 全 {len(rows)} 蔵のデータを深化・補完中...")

    update_records = []
    migration_sql_lines = []

    for r in rows:
        b_id, name, name_norm, pref, city, addr, f_year, desc, visit_allow, shop_avail = r
        name_str = name or name_norm or ""
        pref_str = pref or ""

        # 元号 & 時代区分 & 老舗判定
        era_str, era_cat, is_shinise = calculate_era(f_year)

        # デフォルトプロフィール
        def_water, def_hard, def_toji = PREF_DEFAULT_PROFILES.get(pref_str, ("自然湧水・地下伏流水", "軟水", "蔵元杜氏・社員醸造"))

        water_src = def_water
        water_hard = def_hard
        toji = def_toji
        tour = "見学要事前確認" if visit_allow else "見学不可 (直売・外観のみ)"
        has_taste = 1 if shop_avail else 0
        has_cafe = 0
        is_cult = 0
        cult_desc = ""

        # 有名蔵・個別辞書による上書き突合
        matched = False
        for key, spec in FAMOUS_BREWERIES_SPECIAL.items():
            if key in name_str:
                water_src, water_hard, toji, tour, has_taste, has_cafe, is_cult, cult_desc = spec
                matched = True
                break

        # description や住所からの文化財・見学・角打ちの自動マイニング
        full_text = f"{name_str} {desc or ''} {addr or ''}"
        if not matched:
            if "登録有形文化財" in full_text or "有形文化財" in full_text or "近代化産業遺産" in full_text:
                is_cult = 1
                cult_desc = "国登録有形文化財・歴史的建造物指定"
            if "見学" in full_text and ("可能" in full_text or "案内" in full_text or "予約" in full_text):
                tour = "酒蔵見学可 (要予約)"
                visit_allow = 1
            if "ショップ" in full_text or "売店" in full_text or "直売" in full_text or "試飲" in full_text or "角打ち" in full_text:
                has_taste = 1
                shop_avail = 1
            if "カフェ" in full_text or "レストラン" in full_text or "食事" in full_text or "BAR" in full_text:
                has_cafe = 1

        update_records.append((
            era_str, era_cat, is_shinise,
            water_src, water_hard, toji,
            tour, has_taste, has_cafe,
            is_cult, cult_desc,
            visit_allow, shop_avail,
            b_id
        ))

        # マイグレーションSQL行
        clean_era = era_str.replace("'", "''")
        clean_cat = era_cat.replace("'", "''")
        clean_water = water_src.replace("'", "''")
        clean_hard = water_hard.replace("'", "''")
        clean_toji = toji.replace("'", "''")
        clean_tour = tour.replace("'", "''")
        clean_cult_desc = cult_desc.replace("'", "''")

        migration_sql_lines.append(
            f"UPDATE breweries SET founded_era='{clean_era}', era_category='{clean_cat}', is_shinise={is_shinise}, "
            f"water_source_name='{clean_water}', water_hardness_type='{clean_hard}', toji_guild='{clean_toji}', "
            f"tour_info='{clean_tour}', has_tasting={has_taste}, has_cafe_restaurant={has_cafe}, "
            f"is_cultural_property={is_cult}, cultural_property_desc='{clean_cult_desc}', "
            f"visitation_allowed={visit_allow}, shop_available={shop_avail} WHERE id={b_id};"
        )

    # 3. DB一括更新
    cursor.executemany("""
        UPDATE breweries
        SET founded_era = ?,
            era_category = ?,
            is_shinise = ?,
            water_source_name = ?,
            water_hardness_type = ?,
            toji_guild = ?,
            tour_info = ?,
            has_tasting = ?,
            has_cafe_restaurant = ?,
            is_cultural_property = ?,
            cultural_property_desc = ?,
            visitation_allowed = ?,
            shop_available = ?
        WHERE id = ?
    """, update_records)
    conn.commit()
    print(f"[OK] 全 {len(update_records)} 蔵のデータ更新が完了しました！")

    # 4. マイグレーションファイルの保存
    migration_file_path = os.path.join(MIGRATION_DIR, "002_enrich_brewery_master.sql")
    with open(migration_file_path, "w", encoding="utf-8") as mf:
        mf.write("-- 002_enrich_brewery_master.sql\n")
        mf.write("-- 酒蔵マスターの歴史・元号・仕込み水・杜氏流派・観光文化財データの拡充\n\n")
        for col_name, col_type in new_columns:
            mf.write(f"ALTER TABLE breweries ADD COLUMN {col_name} {col_type};\n")
        mf.write("\n")
        mf.write("\n".join(migration_sql_lines))
        mf.write("\n")
    print(f"[OK] マイグレーションSQLを保存しました: {migration_file_path}")

    # 5. CSV同期エクスポート
    csv_export_path = os.path.join(BACKUP_DIR, "breweries.csv")
    cursor.execute("PRAGMA table_info(breweries)")
    all_headers = [c[1] for c in cursor.fetchall()]

    cursor.execute("SELECT * FROM breweries ORDER BY id ASC")
    all_rows = cursor.fetchall()

    with open(csv_export_path, "w", encoding="utf-8-sig", newline="") as cf:
        writer = csv.writer(cf)
        writer.writerow(all_headers)
        for r in all_rows:
            writer.writerow(r)
    print(f"[OK] バックアップCSVを最新データで同期エクスポートしました: {csv_export_path}")

    conn.close()

if __name__ == "__main__":
    enrich_brewery_database()
