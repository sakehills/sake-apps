# 3. 全製品の走査と、公式蔵元一次情報に基づく固有ストーリー・解説の更新
cur.execute("""
    SELECT p.id, p.brand_name, p.spec_name, p.category, p.polish_ratio, p.rice_variety,
           p.alcohol, p.smv, p.acidity, p.ssi_type, p.brewing_method, p.brewery_name,
           p.prefecture, b.description AS brewery_desc, b.website AS brewery_url
    FROM products p
    LEFT JOIN breweries b ON p.brewery_name = b.name OR p.brand_name = b.kura_name
    ORDER BY p.id
""")
